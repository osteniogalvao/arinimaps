import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import pg from "pg";

const endereco = process.env.ARINI_TESTE_CARTEIRA_DB;
const local = endereco && ["localhost","127.0.0.1","[::1]"].includes(new URL(endereco).hostname);

test("tarefas da Central registram critérios e decisões reais nas transações de origem", {skip: !local}, async t => {
  const admin = new pg.Client({connectionString:endereco});
  await admin.connect();
  const nome = "arini_test_" + randomUUID().replaceAll("-","");
  await admin.query("create database " + nome);
  const dst = new URL(endereco);
  dst.pathname = "/" + nome;
  const pool = new pg.Pool({connectionString:dst.href});
  const q = (sql, args=[]) => pool.query(sql,args);
  const uma = async (sql, args=[]) => (await q(sql,args)).rows[0];
  const [empregado, diretor, inativo, historica] = Array.from({length:4},()=>randomUUID());
  const criar = async (chave, regra, setor="comercial", pessoa=null) => (await uma(
    "select fn_tarefa_automatica($1,$2,$3,'Tratar pendência','Documento sintético',$4,current_date,'normal') id",
    [chave,regra,setor,pessoa])).id;
  const tarefa = chave => uma("select * from tasks where chave_evento=$1",[chave]);
  const baixa = async (chave,referencia) => (await uma(
    "select central_concluir_evento($1,$2,'Contato registrado','visits',$3) ok",[chave,empregado,referencia])).ok;
  try {
    for (const role of ["anon","authenticated","service_role"]) {
      if (!(await q("select from pg_roles where rolname=$1",[role])).rowCount) await q("create role " + role);
    }
    await q(`create table profiles(user_id uuid primary key,role text,ativo boolean default true,setores text[]);
      create table tasks(id uuid primary key default gen_random_uuid(),titulo text,descricao text,setor text,responsavel uuid,criado_por uuid,
        prazo date,prioridade text,status text default 'aberta',origem text default 'manual',regra text,chave_evento text,criterio_conclusao text,
        evidencia text,concluida_em timestamptz,property_id uuid,opportunity_id uuid,aceite_em timestamptz);
      create unique index tarefas_chaves on tasks(chave_evento) where chave_evento is not null;
      create table task_events(task_id uuid,tipo text,autor uuid,para_setor text,texto text,dados jsonb,created_at timestamptz default now());
      create table audit_log(user_id uuid,acao text,entidade text,entidade_id uuid,property_id uuid,opportunity_id uuid,dados_depois jsonb);
      create table despesas(id uuid primary key,codigo text,aprovado_por uuid,status text);
      create table ponto_ajustes(id uuid primary key,status text,tipo text,user_id uuid,horario timestamptz,decidido_por uuid);
      create table ponto_marcacoes(user_id uuid,marcado_em timestamptz not null,origem text,ajuste_id uuid);
      create table property_revisions(id uuid primary key,property_id uuid,versao integer,status text,revisada_por uuid);
      create table cartographic_requests(id uuid primary key,protocolo text,status text);
      create table cartographic_request_events(id uuid primary key default gen_random_uuid(),request_id uuid,user_id uuid,de_status text,para_status text);
      create table assinaturas_cotadas(id uuid primary key,cancelado timestamptz);
      create table faturas_cotadas(id uuid primary key,assinatura uuid,componente text,numero int,status text);
      create table assinatura_contatos(id bigint generated by default as identity,assinatura uuid,titular uuid,tipo text,referencia date,passo int,texto text,status text,alterado_em timestamptz);
      create table assinatura_agenda_contato(assinatura uuid,titular uuid,tipo text,referencia date,passo int,texto text,permitido boolean,modelo_id text,telefone text,nome text);
      create table assinatura_regras_contato(tipo text,dias int[]);
      create table assinatura_reajustes(assinatura uuid,vigencia date,avisado_em timestamptz);
      create function retomada_comercial() returns void language sql as 'select';
      create function assinatura_titular_telefone(text) returns uuid language sql as 'select null::uuid';`);
    await q("insert into tasks(id,titulo,origem,status) values($1,'Histórico legado','automatica','concluida')",[historica]);
    await q(await readFile(new URL("../supabase/migrations/0139_evidencia_tarefas_automaticas.sql",import.meta.url),"utf8"));
    await t.test("fila vazia recebe critério, dados históricos e tarefa manual permanecem íntegros", async () => {
      await criar("fila","Visita sem relatório");
      assert.equal((await tarefa("fila")).responsavel,null);
      assert.match((await tarefa("fila")).criterio_conclusao,/relatório à visita/i);
      const antiga = await uma("select * from tasks where id=$1",[historica]);
      assert.equal(antiga.criterio_conclusao,null); assert.equal(antiga.evidencia,null);
      assert.equal((await q("select from task_events where task_id=$1",[historica])).rowCount,0);
      const manual = await uma("insert into tasks(titulo,setor) values('Manual','comercial') returning *");
      assert.equal(manual.criterio_conclusao,null);
    });
    await q("insert into profiles(user_id,role,setores,ativo) values($1,'analista_arini','{comercial}',true),($2,'admin_central','{}',true),($3,'analista_arini','{comercial}',false)",[empregado,diretor,inativo]);
    await t.test("prioriza equipe habilitada, conserva atribuição explícita e cria uma trilha por chave", async () => {
      const ids = await Promise.all([criar("visita","Visita sem relatório"),criar("visita","Visita sem relatório")]);
      assert.equal(ids.filter(Boolean).length,1);
      assert.equal((await tarefa("visita")).responsavel,empregado);
      await criar("desp","despesa_sem_aprovacao","diretoria");
      assert.equal((await tarefa("desp")).responsavel,diretor);
      await criar("direto","visita sem relatório","comercial",diretor);
      assert.equal((await tarefa("direto")).responsavel,diretor);
      const linha = await uma("insert into tasks(titulo,setor,origem,regra,chave_evento,criterio_conclusao) values('Especial','comercial','automatica','nova_regra','nova','Critério específico') returning id");
      const evento = await uma("select dados from task_events where task_id=$1 and tipo='criada'",[linha.id]);
      assert.equal(evento.dados.criterio_conclusao,"Critério específico");
      assert.equal(evento.dados.responsavel,empregado);
      assert.equal((await q("select from audit_log where entidade_id=$1",[ids.find(Boolean)])).rowCount,1);
    });
    await t.test("encerramento concorrente registra uma única evidência e impede execução por pessoas autenticadas", async () => {
      const referencia = randomUUID();
      assert.equal((await Promise.all([baixa("visita",referencia),baixa("visita",referencia)])).filter(Boolean).length,1);
      const encerrada = await tarefa("visita");
      assert.ok(encerrada.evidencia.includes(referencia)); assert.ok(encerrada.concluida_em);
      const eventos = (await q("select autor,dados from task_events where task_id=$1 and tipo='status'",[encerrada.id])).rows;
      assert.equal(eventos.length,1); assert.equal(eventos[0].autor,empregado); assert.equal(eventos[0].dados.referencia,referencia);
      assert.equal((await q("select from audit_log where entidade_id=$1 and acao='tarefa_concluida_por_evento'",[encerrada.id])).rowCount,1);
      await assert.rejects(q("select central_concluir_evento('fila',null,' ','visits',$1)",[referencia]),{code:"22023"});
      assert.equal((await tarefa("fila")).status,"aberta");
      assert.equal((await uma("select has_function_privilege('authenticated','central_concluir_evento(text,uuid,text,text,text)','execute') ok")).ok,false);
      assert.equal((await uma("select has_function_privilege('service_role','central_registrar_baixa(uuid,text,uuid,text,text,text)','execute') ok")).ok,false);
    });
    await t.test("despesa só encerra após decisão ou pagamento gravado e guarda o autor correto", async () => {
      const id=randomUUID(), aprovacao="despesa_aprovacao:"+id, pagamento="despesa_vencida:"+id;
      await q("insert into despesas(id,codigo,status) values($1,'DES-1','pendente')",[id]);
      await criar(aprovacao,"despesa_sem_aprovacao","diretoria"); await criar(pagamento,"despesa_vencida","financeiro");
      const tx=await pool.connect();
      try { await tx.query("begin"); await tx.query("update despesas set status='aprovada',aprovado_por=$1 where id=$2",[diretor,id]); await tx.query("rollback"); } finally {tx.release();}
      assert.equal((await tarefa(aprovacao)).status,"aberta");
      await q("update despesas set status='aprovada',aprovado_por=$1 where id=$2",[diretor,id]);
      assert.equal((await tarefa(aprovacao)).status,"concluida"); assert.equal((await tarefa(pagamento)).status,"aberta");
      await q("update despesas set status='paga',pago_por=$1 where id=$2",[empregado,id]);
      const evento=await uma("select autor,dados from task_events where task_id=$1 and tipo='status'",[(await tarefa(pagamento)).id]);
      assert.equal(evento.autor,empregado); assert.equal(evento.dados.referencia,id);
    });
    await t.test("decisão do ponto só se confirma junto da marcação e da evidência", async () => {
      const id=randomUUID(),chave="ponto_ajuste:"+id;
      await criar(chave,"ajuste_ponto_parado","diretoria");
      await q("insert into ponto_ajustes(id,tipo,user_id,status) values($1,'incluir',$2,'pendente')",[id,empregado]);
      await assert.rejects(q("update ponto_ajustes set status='aprovado',decidido_por=$1 where id=$2",[diretor,id]),{code:"23502"});
      assert.equal((await tarefa(chave)).status,"aberta");
      const decisao=status=>q("update ponto_ajustes set status=$1,horario=now(),decidido_por=$2 where id=$3 and status='pendente'",[status,diretor,id]);
      await decisao("aprovado"); await decisao("reprovado");
      assert.equal((await q("select from ponto_marcacoes where ajuste_id=$1",[id])).rowCount,1);
      assert.ok((await tarefa(chave)).evidencia.includes(id));
    });
    await t.test("versão e protocolo só encerram a tarefa correspondente, inclusive quando criada antes da migração", async () => {
      const [revisao,predio,solicitacao,evento] = Array.from({length:4},()=>randomUUID());
      await q("insert into property_revisions values($1,$2,2,'pendente',null)",[revisao,predio]);
      const evt=await uma("insert into tasks(titulo,descricao,setor,property_id) values('Alteração proposta — IM-1','Versão 2 do anúncio IM-1 aguarda decisão','operacoes',$1) returning id",[predio]);
      const outra=await uma("insert into tasks(titulo,descricao,setor,property_id) values('Alteração proposta — IM-1','Versão 20 do anúncio IM-1 aguarda decisão','operacoes',$1) returning id",[predio]);
      await q("update property_revisions set status='cancelada',revisada_por=$1 where id=$2",[empregado,revisao]);
      assert.equal((await uma("select status from tasks where id=$1",[evt.id])).status,"cancelada");
      assert.equal((await uma("select status from tasks where id=$1",[outra.id])).status,"aberta");
      await q("insert into cartographic_requests values($1,'CART-12','publicada')",[solicitacao]);
      const carto=await criar("solicitacao_cartografica:"+solicitacao,"solicitacao_cartografica","cartografia");
      const semelhante=await uma("insert into tasks(titulo,setor) values('Solicitação CART-120 — Inclusão','cartografia') returning id");
      await q("insert into cartographic_request_events values($1,$2,$3,'aprovada','publicada')",[evento,solicitacao,diretor]);
      const dado=await uma("select dados from task_events where task_id=$1 and tipo='status'",[carto]);
      assert.equal(dado.dados.referencia,evento);
      assert.equal((await uma("select status from tasks where id=$1",[semelhante.id])).status,"aberta");
    });
    await t.test("worker diferencia cancelamento, primeira fatura paga e fatura de adicional", async () => {
      const [cancelada,paga,aberta,fatura] = Array.from({length:4},()=>randomUUID());
      await q("insert into assinaturas_cotadas values($1,now()),($2,null),($3,null)",[cancelada,paga,aberta]);
      await q("insert into faturas_cotadas values($1,$2,'plano',0,'paga'),(gen_random_uuid(),$3,'adicionais',0,'paga')",[fatura,paga,aberta]);
      const chave = id => "recuperacao_assinatura:"+id;
      for (const id of [cancelada,paga,aberta]) await criar(chave(id),"Recuperação de assinatura");
      await q("select assinatura_preparar_contatos()"); await q("select assinatura_preparar_contatos()");
      const pagto=await tarefa(chave(paga)), cancel=await tarefa(chave(cancelada));
      assert.ok(pagto.evidencia.includes(fatura)); assert.ok(cancel.evidencia.includes(cancelada));
      assert.match(cancel.evidencia,/cancelamento/i); assert.equal((await tarefa(chave(aberta))).status,"aberta");
      assert.equal((await q("select from task_events where task_id=$1 and autor is null and tipo='status'",[pagto.id])).rowCount,1);
    });
  } finally {
    await pool.end(); await admin.query("drop database " + nome); await admin.end();
  }
});
