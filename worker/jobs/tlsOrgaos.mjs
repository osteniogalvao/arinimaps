const CA = [...rootCertificates, SECTIGO_OV_R36];
const ORGAOS = new Set(["geoserver.funai.gov.br", "geo.anm.gov.br"]);
const descompactadores = new Map([["gzip", createGunzip], ["deflate", createInflate], ["br", createBrotliDecompress]]);

/**
 * GET para sondas, mapas e relatórios. Somente esses dois hosts recebem a
 * cadeia complementar. Redirecionamentos não herdam a cadeia.
 * @param {string} url
 * @param {RequestInit} opcoes
 * @returns {Promise<Response>}
 */
export async function buscarFonte(url, opcoes = {}) {
  const destino = new URL(url);
  if (destino.protocol !== "https:" || !ORGAOS.has(destino.host) || (opcoes.method ?? "GET") !== "GET") {
    return fetch(url, opcoes);
  }
  const headers = Object.fromEntries(new Headers(opcoes.headers));
  const res = await new Promise((resolve, reject) => {
    get(destino, { headers, ca: CA, signal: opcoes.signal ?? undefined }, resolve).on("error", reject);
  });
  const partes = [];
  const decodificar = descompactadores.get(res.headers["content-encoding"]);
  const coletar = async (stream) => { for await (const parte of stream) partes.push(parte); };
  if (decodificar) await pipeline(res, decodificar(), coletar);
  else await coletar(res);
  return new Response(partes.length ? Buffer.concat(partes) : null, { status: res.statusCode, statusText: res.statusMessage });
}
